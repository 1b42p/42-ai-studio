import { defineWorkflowTool, toolOutput } from "eve/tools";
import { askQuestion } from "eve/tools/ask_question";

const question = askQuestion();

export default defineWorkflowTool({
  ...question,
  description: "Создать интерактивный вопрос и приостановить ход до ответа пользователя. " +
    "После каждого проверенного черновика, включая новую версию после правок, напиши ссылку в обычном тексте ответа, " +
    "затем вызови этот инструмент в том же шаге. В question передавай только вопрос: " +
    "ссылка внутри аргумента не публикует видео в беседе. Текст вместо вызова не создаёт подтверждение. " +
    "Для выбора формата кадра, " +
    "длительности, голоса или рендера финала предложи options: два или три взаимоисключающих " +
    "варианта с label и описанием в одно предложение. Для темы, сюжета и развёрнутого ответа " +
    "опусти options. Пользователь всегда может написать свой ответ; вариант «Другое» не нужен. " +
    "Задавай вопросы по одному, учитывая предыдущие ответы. " +
    "Принятое «Рендерить финал» завершает согласование текущего черновика: сразу запускай полный рендер этой версии. " +
    'Пример входа для согласования экспорта: {"question":"Рендерить финал в полном качестве?",' +
    '"options":[{"label":"Рендерить финал","description":"Выполнить полный экспорт текущей версии."},' +
    '{"label":"Хочу поправить","description":"Изменить проект перед полным экспортом."}]}.',
  toModelOutput(output) {
    if ("status" in output && output.status === "answered" && output.answer.trim() === "Рендерить финал") {
      return toolOutput.text("Пользователь утвердил полный экспорт текущего черновика. " +
        "Следующее действие — запустить полный рендер утверждённой версии. Согласование уже завершено.");
    }
    return question.toModelOutput?.(output) ?? toolOutput.json(output);
  },
});
